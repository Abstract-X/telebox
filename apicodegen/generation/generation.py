def _create_type_hints_module(
    generator: CodeGenerator,
    hint_types: list[str]
) -> None:
    import_builder = ImportBuilder("telebox")

    for i in ("Union", "Callable"):
        import_builder.add("typing", i)

    for i in hint_types:
        if i == "MediaGroup":
            import_builder.add("telebox.dispatcher.types.media_group", "MediaGroup")
        else:
            import_builder.add(f"telebox.bot.types.{get_snake_case_string(i)}", i)

    import_builder.add("telebox.utils.deps", "Deps")

    generator.create_module(
        Module(
            type_hints_path,
            "dispatcher/type_hints.j2",
            imports=import_builder.get(),
            hint_types=hint_types
        )
    )


def _get_event_types(update_types: list[str]) -> list[str]:
    types = update_types[:]

    for i in ("MEDIA_GROUP", "CHANNEL_MEDIA_GROUP"):
        types.append(i)

    return sorted(types)


def _get_event_hint_types(update: PreparedType) -> list[str]:
    types = {
        i.types[0]
        for i in update.fields
        if i.is_optional
    }
    types.add("MediaGroup")

    return sorted(types)


def _resolve_message_type_hints(
    types: dict[str, PreparedType],
    import_builders: dict[str, ImportBuilder]
) -> set[str]:
    message = types["Message"]
    message_import_builder = import_builders["Message"]
    evaluating_types = {"Message"}

    for i in message.fields:
        i.type_hint = re.sub(r"\bMessage\b", '"Message"', i.type_hint)

    for type_ in types:
        if not import_builders[type_].check("telebox.bot.types.message", "Message"):
            continue

        for i in message.fields:
            if not message_import_builder.check(
                f"telebox.bot.types.{types[type_].module_name}",
                type_
            ):
                continue

            i.type_hint = re.sub(rf"\b{type_}\b", f'"{type_}"', i.type_hint)
            evaluating_types.add(type_)
            message_import_builder.add(
                f"telebox.bot.types.{types[type_].module_name}",
                type_,
                for_type_checking=True
            )

    return evaluating_types
